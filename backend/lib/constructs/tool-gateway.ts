const LAMBDAS_DIR = path.join(__dirname, '..', '..', 'lambdas');

/** Cognito resource server identifier; scopes are `cei-tools/<name>` (auth-and-tool-scope.md section 3). */
export const TOOL_RESOURCE_SERVER_ID = 'cei-tools';
/** B70/B86: shared scope every principal gets by default (LS Ops, Web Search, KB retrieval — F10/F12). */
export const COMMON_SCOPE_NAME = 'common';
/** B27/B85: reserved now so F15 (NCBI targets) never has to touch the resource server. */
export const RESERVED_SOURCE_IDS = ['ncbi'];

interface ToolSchemaEntry {
  sourceId: string;
  tool: { name: string; description: string; inputSchema: Record<string, unknown> };
}

/** Generated by backend/scripts/gen_tool_schemas.py from the tools' pydantic InputSchemas. */
export function loadToolSchemas(): ToolSchemaEntry[] {
  return JSON.parse(fs.readFileSync(path.join(LAMBDAS_DIR, 'data-source-tool-schemas.json'), 'utf-8'));
}

export const sourceScopeName = (sourceId: string) => `src.${sourceId}`;
export const fullScope = (scopeName: string) => `${TOOL_RESOURCE_SERVER_ID}/${scopeName}`;

/** B69: Cedar `like "*scope*"` is a substring match, so no scope name may sit inside another. */
export function assertNoScopeCollisions(scopeNames: string[]): void {
  const clashes = scopeNames.flatMap((a) => scopeNames.filter((b) => a !== b && b.includes(a)).map((b) => `${a} in ${b}`));
  if (clashes.length > 0) {
    throw new Error(`Tool scope names must not contain one another (B69): ${clashes.join(', ')}`);
  }
}

export interface ToolGatewayProps {
  userPool: cognito.UserPool;
  /** `https://<prefix>.auth.<region>.amazoncognito.com` — the token endpoint is `<this>/oauth2/token`. */
  cognitoDomainUrl: string;
  /** Must exist before a token can be minted (the token endpoint lives on the domain). */
  userPoolDomain: cognito.UserPoolDomain;
  api: apigw.RestApi;
  requestValidator: apigw.IRequestValidator;
  /** Layer with pydantic + http_errors (PythonDepsLayer) for the token-refresh Lambda. */
  pythonDepsLayer: lambda.ILayerVersion;
  policyMode: ToolPolicyMode;
  /** B67: roles allowed to call POST /internal/token-refresh. Empty until F5 adds the agent runtime role. */
  refreshCallerRoleArns?: string[];
  activeRunsTable?: dynamodb.ITable;
  metadataTable?: dynamodb.ITable;
  spaClientId?: string;
}

/**
 * F4: AgentCore Gateway with the 10 data-source Lambda targets, gated by Cognito M2M scopes and Cedar.
 */
export class ToolGateway extends Construct {
  public readonly gateway: agentcore.CfnGateway;
  public readonly routerClient: cognito.UserPoolClient;
  public readonly routerSecret: secretsmanager.Secret;
  public readonly routerRole: iam.Role;
  public readonly tokenRefreshFunction: lambda.Function;
  public readonly preTokenFunction: lambda.Function;
  public readonly gatewayLogGroup: logs.ILogGroup;
  public readonly sourceFunctions: Record<string, lambda.Function> = {};
  public readonly operationsFunction: lambda.DockerImageFunction;
  public readonly ncbiFunction: lambda.Function;
  public readonly ncbiRateTable: dynamodb.Table;
  public readonly scopeNames: string[];

  constructor(scope: Construct, id: string, props: ToolGatewayProps) {
    super(scope, id);
    const stack = cdk.Stack.of(this);
    const schemas = loadToolSchemas();
    const sourceIds = schemas.map((s) => s.sourceId);

    // ---------------------------------------------------------------
    // Resource server: 10 source scopes + reserved ncbi + shared common (B69/B70/B86)
    // ---------------------------------------------------------------

    this.scopeNames = [...[...sourceIds, ...RESERVED_SOURCE_IDS].map(sourceScopeName), COMMON_SCOPE_NAME];
    assertNoScopeCollisions(this.scopeNames);

    const resourceServer = props.userPool.addResourceServer('ToolResourceServer', {
      identifier: TOOL_RESOURCE_SERVER_ID,
      scopes: this.scopeNames.map((scopeName) => new cognito.ResourceServerScope({ scopeName, scopeDescription: `Tool access: ${scopeName}` })),
    });
    const oauthScope = (scopeName: string) =>
      cognito.OAuthScope.resourceServer(resourceServer, new cognito.ResourceServerScope({ scopeName, scopeDescription: scopeName }));

    // ---------------------------------------------------------------
    // Router M2M client (B30): client credentials, every tool scope, 1 h tokens (B67)
    // ---------------------------------------------------------------

    this.routerClient = props.userPool.addClient('RouterM2MClient', {
      generateSecret: true,
      oAuth: { flows: { clientCredentials: true }, scopes: this.scopeNames.map(oauthScope) },
      accessTokenValidity: Duration.minutes(60),
      supportedIdentityProviders: [cognito.UserPoolClientIdentityProvider.COGNITO],
      preventUserExistenceErrors: true,
    });
    // ADR: only ALLOW_REFRESH_TOKEN_AUTH in ExplicitAuthFlows | Rationale: same lock-down as the SPA client — a
    // machine client has no user sign-in, and CDK omitting the property leaves Cognito's SRP/custom defaults on
    (this.routerClient.node.defaultChild as cognito.CfnUserPoolClient).explicitAuthFlows = ['ALLOW_REFRESH_TOKEN_AUTH'];

    // Keep the logical ID stable, but remove the former test-only account trust. Only Lambda may assume it.
    this.routerRole = new iam.Role(this, 'RouterPlaceholderRole', {
      assumedBy: new iam.ServicePrincipal('lambda.amazonaws.com'),
      description: 'Session Router Lambda role. With token-refresh, the only reader of the Router M2M secret.',
    });

    const refreshRole = new iam.Role(this, 'TokenRefreshRole', { assumedBy: new iam.ServicePrincipal('lambda.amazonaws.com') });
    if (props.activeRunsTable && props.metadataTable) {
      refreshRole.addToPolicy(new iam.PolicyStatement({ actions: ['dynamodb:GetItem'], resources: [props.activeRunsTable.tableArn, props.metadataTable.tableArn] }));
    }

    this.routerSecret = new secretsmanager.Secret(this, 'RouterM2MSecret', {
      description: 'Router M2M app client secret (F4, B30). Readable only by the Router and token-refresh roles.',
      // ADR: client secret via the L1 ClientSecret attribute | Rationale: S2 — the L2 userPoolClientSecret adds an AwsCustomResource with a CDK-owned AWSLambdaBasicExecutionRole (IAM4) | Alternative: suppressing it rejected — avoidable
      secretStringValue: cdk.SecretValue.resourceAttribute((this.routerClient.node.defaultChild as cognito.CfnUserPoolClient).attrClientSecret),
      // ADR: DESTROY | Rationale: the value is derived from the app client and is regenerated with it; nothing user-owned is lost
      removalPolicy: RemovalPolicy.DESTROY,
    });
    this.routerSecret.grantRead(this.routerRole);
    this.routerSecret.grantRead(refreshRole);
    // B30 / S2 Q3: an explicit Deny beats any identity Allow (proven against an admin user)
    this.routerSecret.addToResourcePolicy(
      new iam.PolicyStatement({
        sid: 'DenyAllButRouterAndRefresh',
        effect: iam.Effect.DENY,
        principals: [new iam.AnyPrincipal()],
        actions: ['secretsmanager:GetSecretValue'],
        resources: ['*'],
        conditions: { StringNotEquals: { 'aws:PrincipalArn': [this.routerRole.roleArn, refreshRole.roleArn] } },
      }),
    );

    // ---------------------------------------------------------------
    // Pre-token-generation trigger, V3_0 (M2M access-token customization; pool is on Essentials)
    // ---------------------------------------------------------------

    const preTokenFn = this.pythonFunction('PreTokenGeneration', 'pre-token-generation', {
      timeout: Duration.seconds(5),
      environment: {},
    });
    this.preTokenFunction = preTokenFn;
    props.userPool.addTrigger(cognito.UserPoolOperation.PRE_TOKEN_GENERATION_CONFIG, preTokenFn, cognito.LambdaVersion.V3_0);

    // ---------------------------------------------------------------
    // Ten data-source Lambdas (Gateway targets)
    // ---------------------------------------------------------------

    const dataSourceLayer = new DataSourceLayer(this, 'DataSourceLayer');
    this.ncbiRateTable = new dynamodb.Table(this, 'NcbiRateLimiter', {
      partitionKey: { name: 'pk', type: dynamodb.AttributeType.STRING },
      billingMode: dynamodb.BillingMode.PAY_PER_REQUEST,
      encryption: dynamodb.TableEncryption.AWS_MANAGED,
      pointInTimeRecoverySpecification: { pointInTimeRecoveryEnabled: true },
      timeToLiveAttribute: 'expires_at',
      removalPolicy: RemovalPolicy.DESTROY,
    });
    for (const sourceId of sourceIds) {
      this.sourceFunctions[sourceId] = this.pythonFunction(`DataSource-${sourceId}`, `data-source-${sourceId}`, {
        layers: [dataSourceLayer.layer],
        // openFDA queries three endpoints sequentially; each may consume the full retry budget.
        // The other sources make at most two sequential requests (CMS detail requests are concurrent).
        timeout: Duration.seconds(sourceId === 'openfda' ? 150 : 90),
        memorySize: 256,
        environment: {
          // The source Lambdas only call tool.fetch() (the real upstream call); no direct-mode switch is involved
          CEI_API_KEY_SECRET_PREFIX: 'cei/user-keys',
          ...(sourceId === 'pubmed' ? { NCBI_RATE_LIMIT_TABLE: this.ncbiRateTable.tableName } : {}),
        },
      });
    }
    this.sourceFunctions.pubmed.addToRolePolicy(new iam.PolicyStatement({
      actions: ['dynamodb:UpdateItem'], resources: [this.ncbiRateTable.tableArn],
    }));
    this.ncbiFunction = this.pythonFunction('NcbiReadOnly', 'ncbi', {
      timeout: Duration.seconds(90), memorySize: 256,
      environment: { NCBI_RATE_LIMIT_TABLE: this.ncbiRateTable.tableName },
    });
    this.ncbiFunction.addToRolePolicy(new iam.PolicyStatement({
      actions: ['dynamodb:UpdateItem'], resources: [this.ncbiRateTable.tableArn],
    }));
    // ADR: no Secrets Manager grant on the source Lambdas yet | Rationale: B99 — no user id reaches a Lambda
    // target until F18, so the user-key lookup never runs; F18 adds GetSecretValue on cei/user-keys/* with the
    // user-id mechanism | Alternative: granting now rejected — an unused read on every user's keys

    // ---------------------------------------------------------------
    // Policy engine + Gateway (custom JWT on the Router client) + targets + Cedar permits
    // ---------------------------------------------------------------

    const policyEngine = new agentcore.CfnPolicyEngine(this, 'PolicyEngine', {
      // Policy engine names: [A-Za-z][A-Za-z0-9_]* (no hyphens)
      name: 'cei_tools_engine',
      description: 'F4: one Cedar permit per data-source target, default deny (B69)',
    });

    const gatewayRole = new iam.Role(this, 'GatewayRole', {
      assumedBy: new iam.PrincipalWithConditions(new iam.ServicePrincipal('bedrock-agentcore.amazonaws.com'), {
        StringEquals: { 'aws:SourceAccount': stack.account },
        ArnLike: { 'aws:SourceArn': stack.formatArn({ service: 'bedrock-agentcore', resource: '*', arnFormat: cdk.ArnFormat.NO_RESOURCE_NAME }) },
      }),
    });
    gatewayRole.addToPolicy(
      new iam.PolicyStatement({ actions: ['lambda:InvokeFunction'], resources: [...Object.values(this.sourceFunctions).map((fn) => fn.functionArn), this.ncbiFunction.functionArn] }),
    );
    // S2: GetPolicyEngine / AuthorizeAction / PartiallyAuthorizeActions are required; PartiallyAuthorizeActions filters tools/list
    gatewayRole.addToPolicy(new iam.PolicyStatement({ actions: ['bedrock-agentcore:GetPolicyEngine'], resources: [policyEngine.attrPolicyEngineArn] }));
    // ADR: gateway/* in the gateway role | Rationale: S2 — the role is a required Gateway property, so the Gateway ARN cannot be referenced without a cycle | Alternative: a fixed name in the ARN rejected — the service appends a random suffix
    gatewayRole.addToPolicy(
      new iam.PolicyStatement({
        actions: ['bedrock-agentcore:AuthorizeAction', 'bedrock-agentcore:PartiallyAuthorizeActions'],
        resources: [policyEngine.attrPolicyEngineArn, stack.formatArn({ service: 'bedrock-agentcore', resource: 'gateway', resourceName: '*' })],
      }),
    );

    this.gateway = new agentcore.CfnGateway(this, 'Gateway', {
      name: 'cei-tools',
      description: 'F4: data-source tools for the CEI agents (one target per source)',
      protocolType: 'MCP',
      authorizerType: 'CUSTOM_JWT',
      authorizerConfiguration: {
        customJwtAuthorizer: {
          discoveryUrl: `https://cognito-idp.${stack.region}.amazonaws.com/${props.userPool.userPoolId}/.well-known/openid-configuration`,
          // ADR: allowedClients, no allowedScopes | Rationale: S2 — Cognito client-credentials tokens carry client_id, not aud; Cedar, not the authorizer, decides per-target access
          allowedClients: [this.routerClient.userPoolClientId],
        },
      },
      roleArn: gatewayRole.roleArn,
      // ADR: default exceptionLevel (not DEBUG) | Rationale: S2 used DEBUG to see deny details; production callers only need the JSON-RPC error code (-32002 = policy deny), not internal detail
      policyEngineConfiguration: { arn: policyEngine.attrPolicyEngineArn, mode: props.policyMode },
    });
    this.gateway.node.addDependency(gatewayRole);

    // B42/B70: one deterministic target, gated by the shared common scope.
    this.operationsFunction = new LifeSciencesOperations(this, 'LifeSciencesOperations', {
      gateway: this.gateway, gatewayRole, policyEngine,
    }).function;

    const ncbiTarget = new agentcore.CfnGatewayTarget(this, 'NcbiTarget', {
      name: 'ncbi', gatewayIdentifier: this.gateway.attrGatewayIdentifier,
      credentialProviderConfigurations: [{ credentialProviderType: 'GATEWAY_IAM_ROLE' }],
      targetConfiguration: { mcp: { lambda: { lambdaArn: this.ncbiFunction.functionArn, toolSchema: { inlinePayload: [
        { name: 'taxonomy_lineage', description: 'Retrieve an NCBI taxonomy lineage by taxon name or ID.',
          inputSchema: { type: 'object', properties: { taxon: { type: 'string' } }, required: ['taxon'] } },
        { name: 'sequence_efetch', description: 'Retrieve an NCBI nucleotide or protein sequence by accession.',
          inputSchema: { type: 'object', properties: { accession: { type: 'string' }, database: { type: 'string' }, format: { type: 'string' } },
            required: ['accession', 'database', 'format'] } },
      ] } } } },
    });
    ncbiTarget.node.addDependency(gatewayRole);
    const ncbiPolicy = new agentcore.CfnPolicy(this, 'PermitNcbi', {
      name: 'permit_ncbi', policyEngineId: policyEngine.attrPolicyEngineId,
      definition: { cedar: { statement: cedarPermit('ncbi', this.gateway.attrGatewayArn, fullScope(sourceScopeName('ncbi'))) } },
      validationMode: 'IGNORE_ALL_FINDINGS',
    });
    ncbiPolicy.node.addDependency(ncbiTarget);

    for (const entry of schemas) {
      const fn = this.sourceFunctions[entry.sourceId];
      const target = new agentcore.CfnGatewayTarget(this, `Target-${entry.sourceId}`, {
        // Target name = Cedar action group; the MCP tool is `<target>___search` (tools.md section 1)
        name: entry.sourceId,
        description: entry.tool.description.slice(0, 200),
        gatewayIdentifier: this.gateway.attrGatewayIdentifier,
        credentialProviderConfigurations: [{ credentialProviderType: 'GATEWAY_IAM_ROLE' }],
        targetConfiguration: {
          mcp: {
            lambda: {
              lambdaArn: fn.functionArn,
              // Shape checked by agents/tests/test_tool_schemas.py (only type/properties/required/description)
              toolSchema: { inlinePayload: [entry.tool as unknown as agentcore.CfnGatewayTarget.ToolDefinitionProperty] },
            },
          },
        },
      });
      // The Gateway validates the Lambda target with the role, so the role policy must exist first
      target.node.addDependency(gatewayRole);

      const policy = new agentcore.CfnPolicy(this, `Permit-${entry.sourceId}`, {
        name: `permit_${entry.sourceId}`,
        policyEngineId: policyEngine.attrPolicyEngineId,
        description: `Permit ${entry.sourceId} when the token carries ${fullScope(sourceScopeName(entry.sourceId))}`,
        definition: { cedar: { statement: cedarPermit(entry.sourceId, this.gateway.attrGatewayArn, fullScope(sourceScopeName(entry.sourceId))) } },
        // ADR: IGNORE_ALL_FINDINGS | Rationale: the S2-proven setting; the analyzer flags the B70 open permit shape, and F4 must not fail a deploy on an advisory finding | Alternative: FAIL_ON_ANY_FINDINGS rejected — untested on these permits
        validationMode: 'IGNORE_ALL_FINDINGS',
      });
      // CreatePolicy validates the action against the target's tool schema
      policy.node.addDependency(target);
    }
    // Web Search is integrated separately. Attachment retrieval is deferred for this iteration.

    // Policy decisions (LOG_ONLY "would deny") are only visible in the Gateway's vended APPLICATION_LOGS
    const gatewayLogGroup = new logs.LogGroup(this, 'GatewayLogs', {
      logGroupName: `/aws/vendedlogs/bedrock-agentcore/gateway/${stack.stackName}-tools`,
      retention: logs.RetentionDays.ONE_MONTH,
      removalPolicy: RemovalPolicy.DESTROY,
    });
    this.gatewayLogGroup = gatewayLogGroup;
    const deliverySource = new logs.CfnDeliverySource(this, 'GatewayLogSource', {
      name: `${stack.stackName}-tools-gateway-logs`,
      logType: 'APPLICATION_LOGS',
      resourceArn: this.gateway.attrGatewayArn,
    });
    const deliveryDestination = new logs.CfnDeliveryDestination(this, 'GatewayLogDestination', {
      name: `${stack.stackName}-tools-gateway-logs-dest`,
      deliveryDestinationType: 'CWL',
      destinationResourceArn: gatewayLogGroup.logGroupArn,
    });
    const delivery = new logs.CfnDelivery(this, 'GatewayLogDelivery', {
      deliverySourceName: deliverySource.name,
      deliveryDestinationArn: deliveryDestination.attrArn,
    });
    delivery.node.addDependency(deliverySource);
    delivery.node.addDependency(deliveryDestination);

    // ---------------------------------------------------------------
    // Token refresh (B67): POST /internal/token-refresh, AWS_IAM
    // ---------------------------------------------------------------

    this.tokenRefreshFunction = this.pythonFunction('TokenRefresh', 'token-refresh', {
      role: refreshRole,
      layers: [props.pythonDepsLayer],
      timeout: Duration.seconds(15),
      environment: {
        ROUTER_CLIENT_ID: this.routerClient.userPoolClientId,
        ROUTER_SECRET_ARN: this.routerSecret.secretArn,
        TOKEN_ENDPOINT: `${props.cognitoDomainUrl}/oauth2/token`,
        ALLOWED_SCOPES: this.scopeNames.map(fullScope).join(','),
        ALLOWED_CALLER_ROLE_ARNS: (props.refreshCallerRoleArns ?? []).join(','),
        ACTIVE_RUNS_TABLE: props.activeRunsTable?.tableName ?? '',
        METADATA_TABLE: props.metadataTable?.tableName ?? '',
        USER_POOL_ID: props.userPool.userPoolId,
        SPA_CLIENT_ID: props.spaClientId ?? '',
      },
    });
    this.tokenRefreshFunction.node.addDependency(props.userPoolDomain);

    const internal = props.api.root.addResource('internal');
    const refreshMethod = internal.addResource('token-refresh').addMethod('POST', new apigw.LambdaIntegration(this.tokenRefreshFunction), {
      // ADR: AWS_IAM, no API resource policy | Rationale: api.md asks for a resource policy restricting the route to the
      // runtime role, but a REST API resource policy covers every route and would need explicit Allows for the
      // Cognito routes; the Lambda instead allowlists caller role ARNs (empty until F5, so it fails closed)
      // Alternative: an API resource policy rejected — risks the live F3 routes for no extra protection
      authorizationType: apigw.AuthorizationType.IAM,
      requestValidator: props.requestValidator,
    });
    NagSuppressions.addResourceSuppressions(refreshMethod, [
      {
        id: 'AwsSolutions-COG4',
        reason: 'ADR: AWS_IAM, not Cognito, on POST /internal/token-refresh | Rationale: B67/api.md — the caller is an AgentCore runtime execution role, not a signed-in user | Alternative: Cognito authorizer rejected — machine callers have no user pool token',
      },
    ]);

    // ---------------------------------------------------------------
    // Outputs (F4 integration script, F5 Router)
    // ---------------------------------------------------------------

    const out = (key: string, value: string, description: string) => new cdk.CfnOutput(stack, key, { value, description });
    out('ToolGatewayUrl', this.gateway.attrGatewayUrl, 'Tool Gateway MCP endpoint (F4)');
    out('ToolGatewayId', this.gateway.attrGatewayIdentifier, 'Tool Gateway id');
    out('ToolPolicyMode', props.policyMode, 'Tool Gateway Cedar policy mode (LOG_ONLY or ENFORCE)');
    out('ToolPolicyEngineId', policyEngine.attrPolicyEngineId, 'Tool Gateway policy engine id');
    out('ToolGatewayLogGroup', gatewayLogGroup.logGroupName, 'Tool Gateway APPLICATION_LOGS (policy decisions)');
    out('RouterClientId', this.routerClient.userPoolClientId, 'Router M2M app client id');
    out('RouterSecretArn', this.routerSecret.secretArn, 'Router M2M client secret (Router and token-refresh roles only)');
    out('RouterRoleArn', this.routerRole.roleArn, 'Session Router Lambda execution role');
    out('ToolTokenEndpoint', `${props.cognitoDomainUrl}/oauth2/token`, 'Cognito OAuth token endpoint for Router tokens');
    out('ToolScopes', this.scopeNames.map(fullScope).join(','), 'Tool scopes on the cei-tools resource server');

    // ---------------------------------------------------------------
    // cdk-nag (ADR format)
    // ---------------------------------------------------------------

    NagSuppressions.addResourceSuppressions(this.routerSecret, [
      {
        id: 'AwsSolutions-SMG4',
        reason: 'ADR: No rotation on the Router M2M client secret | Rationale: the value is the Cognito app client secret, rotated by replacing the app client (Cognito has no rotation API for it) | Alternative: a rotation Lambda rejected — nothing it could call',
      },
    ]);
    NagSuppressions.addResourceSuppressions(
      gatewayRole,
      [
        {
          id: 'AwsSolutions-IAM5',
          reason: 'ADR: gateway/* in the Gateway role | Rationale: S2 — the role is a required Gateway property, so the Gateway ARN cannot be referenced without a circular dependency | Alternative: a fixed name rejected — the service appends a random suffix',
          // partition/region/account are tokens without cdk.json context (Jest) and literals under the CDK CLI,
          // whose cdk.json feature flags resolve them when the stack env is known — match both
          appliesTo: [
            'Resource::arn:<AWS::Partition>:bedrock-agentcore:<AWS::Region>:<AWS::AccountId>:gateway/*',
            { regex: '/^Resource::arn:(<AWS::Partition>|aws[a-z-]*):bedrock-agentcore:[^:]+:[^:]+:gateway\\/\\*$/' },
          ],
        },
      ],
      true,
    );
  }

  /** Python 3.14 Lambda with its own log group and a hand-rolled role (no AWSLambdaBasicExecutionRole, IAM4). */
  private pythonFunction(
    id: string,
    dir: string,
    options: { role?: iam.Role; layers?: lambda.ILayerVersion[]; timeout: Duration; memorySize?: number; environment: Record<string, string> },
  ): lambda.Function {
    const logGroup = new logs.LogGroup(this, `${id}Logs`, { retention: logs.RetentionDays.ONE_MONTH, removalPolicy: RemovalPolicy.DESTROY });
    const role = options.role ?? new iam.Role(this, `${id}Role`, { assumedBy: new iam.ServicePrincipal('lambda.amazonaws.com') });
    logGroup.grantWrite(role);
    const fn = new lambda.Function(this, `${id}Fn`, {
      tracing: lambda.Tracing.ACTIVE,
      runtime: lambda.Runtime.PYTHON_3_14,
      handler: 'handler.handler',
      code: lambda.Code.fromAsset(path.join(LAMBDAS_DIR, dir), { exclude: ['tests', 'test_*.py', '__pycache__', '*.pyc'] }),
      layers: options.layers,
      role,
      logGroup,
      timeout: options.timeout,
      memorySize: options.memorySize ?? 128,
      environment: options.environment,
    });
    suppressXrayWildcard(role);
    return fn;
  }
}
